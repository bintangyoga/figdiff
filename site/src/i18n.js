const RULES = [
  [/^You found (\d) of 3$/, "Kamu menemukan $1 dari 3"],
  [/^Could not read (.+)\.$/, "Tidak bisa membaca $1."],
  [/^Could not load the sample\. Check your connection and try again\.$/, "Tidak bisa memuat contoh. Periksa koneksimu lalu coba lagi."],
];

const SKIP = "code, pre, script, style, .mq, .path, .prop, .from, .to, .report-title, .report-sub";
const ATTRS = ["alt", "aria-label"];
const originals = new WeakMap();
let lang = "en";

function lookup(en) {
  const key = en.trim();
  if (!key) return null;
  if (Object.hasOwn(ID, key)) return ID[key];
  for (const [re, out] of RULES) if (re.test(key)) return key.replace(re, out);
  return null;
}

export function t(en) {
  return lang === "id" ? (lookup(en) ?? en) : en;
}

let reverse = null;
/** The English text for a translated string (or the string itself). */
export function toEn(text) {
  reverse ??= new Map(Object.entries(ID).map(([en, id]) => [id, en]));
  return reverse.get(text.trim()) ?? text;
}

/** Set the English text of an element and translate it for the current language. */
export function retext(el, en) {
  el.textContent = en;
  refresh(el);
}

export function getLang() {
  return lang;
}

function translateTextNode(node) {
  let orig = originals.get(node);
  if (orig === undefined || node.nodeValue !== orig.shown) orig = { en: node.nodeValue, shown: node.nodeValue };
  const lead = /^\s*/.exec(orig.en)[0];
  const trail = /\s*$/.exec(orig.en)[0];
  const out = lang === "id" ? lookup(orig.en) : null;
  const next = out === null ? orig.en : lead + out + trail;
  node.nodeValue = next;
  originals.set(node, { en: orig.en, shown: next });
}

/** Translate everything under `root` for the current language. Safe to call again after the page changes. */
export function refresh(root = document.body) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: (n) => (n.parentElement?.closest(SKIP) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(translateTextNode);
  for (const el of root.querySelectorAll("[alt], [aria-label]")) {
    if (el.id === "lang-toggle") continue;
    for (const a of ATTRS) {
      if (!el.hasAttribute(a)) continue;
      const key = `en_${a.replace("-", "_")}`;
      if (el.dataset[key] === undefined) el.dataset[key] = el.getAttribute(a);
      const out = lang === "id" ? lookup(el.dataset[key]) : null;
      el.setAttribute(a, out ?? el.dataset[key]);
    }
  }
  document.documentElement.lang = lang;
}

export function setLang(next) {
  lang = next === "id" ? "id" : "en";
  try {
    localStorage.setItem("figdiff-lang", lang);
  } catch {
    /* storage may be blocked */
  }
  refresh();
  const btn = document.getElementById("lang-toggle");
  if (btn) {
    btn.textContent = lang === "id" ? "EN" : "ID";
    btn.setAttribute("aria-label", lang === "id" ? "Switch to English" : "Ganti ke Bahasa Indonesia");
  }
  document.dispatchEvent(new CustomEvent("langchange", { detail: lang }));
}

export function initLang() {
  let saved = null;
  try {
    saved = localStorage.getItem("figdiff-lang");
  } catch {
    /* ignored */
  }
  const start = saved ?? ((navigator.language || "").toLowerCase().startsWith("id") ? "id" : "en");
  const btn = document.getElementById("lang-toggle");
  if (btn) {
    btn.hidden = false;
    btn.addEventListener("click", () => setLang(lang === "id" ? "en" : "id"));
  }
  setLang(start);
}
